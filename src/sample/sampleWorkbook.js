/**
 * 예시 양식 (체험용).
 *
 * 대교협 양식을 받아 본 적 없는 사람도 이 도구가 무엇을 하는지 눌러 볼 수 있어야 한다.
 * **데이터는 전부 가상 데이터다** — 실제 학생도, 실제 학교의 실적도 들어 있지 않다.
 *
 * 양식은 대교협 계열의 생김새를 따른다. 머리글 두 줄, 내신 구역 다음에 한국사로
 * 열리는 수능 구역. 그래야 체험이 실제와 같은 길을 지난다 — 이름으로 열을 해석하고,
 * 고3 년도를 사람이 확정하고, 판정을 사전으로 읽는 길.
 *
 * **같은 씨앗에서 늘 같은 파일이 나온다.** 누를 때마다 내용이 달라지면 화면을 두고
 * 이야기할 수 없고, 검사도 둘 수 없다.
 */

import { utils as sheetUtils, write as writeWorkbook } from 'xlsx';

/** 씨앗 하나로 같은 수열을 되풀이한다 (mulberry32). */
function 난수(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

