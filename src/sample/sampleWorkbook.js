/**
 * 예시 격자를 만든다.
 *
 * @param {{students?: number, seed?: number, schoolYear?: number}} [options]
 * @returns {unknown[][]}
 */
export function sampleGrid({ students = 40, seed = 20260101, schoolYear = 2026 } = {}) {
  const rand = 난수(seed);
  const 뽑아 = (list) => list[Math.floor(rand() * list.length)];
  const 등급 = () => 1 + Math.floor(rand() * 7);

  /*
   * 머리글 두 줄. 첫 줄이 구역과 영역을, 둘째 줄이 항목을 적는다.
   * 수능 구역은 「한국사」로 열린다 — 해석기가 구역을 나누는 표지다 (§4).
   */
  const top = [
    '학년', '반', '번호', '이름', '대학명', '지역', '모집시기', '전형유형', '전형명',
    '모집단위', '계열', '전교과', '국영수사과', '1단계', '최종단계', '불합격사유',
    '예비순위', '등록여부', '한국사', '국어', '', '', '수학', '', '', '영어',
    '탐구1', '', '', '탐구2', '', ''
  ];
  const sub = [
    '', '', '', '', '', '', '', '', '', '', '', '', '', '', '', '', '', '',
    '등급', '선택과목', '표준점수', '등급', '선택과목', '표준점수', '등급', '등급',
    '선택과목', '표준점수', '등급', '선택과목', '표준점수', '등급'
  ];

  const grid = [top, sub];

  for (let i = 0; i < students; i += 1) {
    const 반 = 1 + Math.floor(i / 10);
    const 번호 = 1 + (i % 10);
    const 이름 = 이름들[i % 이름들.length];
    const 전교과 = Number((1.4 + rand() * 4).toFixed(2));
    const 조합 = Number((전교과 + (rand() - 0.5) * 0.4).toFixed(2));
    const [탐구1, 탐구2] = 뽑아(탐구과목);
    const 수능 = [
      등급(), 뽑아(국어선택), 100 + Math.floor(rand() * 40), 등급(),
      뽑아(수학선택), 100 + Math.floor(rand() * 40), 등급(), 등급(),
      탐구1, 40 + Math.floor(rand() * 30), 등급(), 탐구2, 40 + Math.floor(rand() * 30), 등급()
    ];
    const 계열 = rand() < 0.5 ? '인문' : '자연';

    // 한 사람이 여러 곳에 지원한다. 그래야 학생 상세와 병합이 뜻을 가진다
    const 지원수 = 2 + Math.floor(rand() * 5);
    let 등록함 = false;
    for (let k = 0; k < 지원수; k += 1) {
      const [대학, 지역] = 뽑아(대학들);
      const [유형, 이름표] = 뽑아(전형);
      // 합격이 드문 것이 실제에 가깝다. 다 붙는 예시는 화면을 오해하게 만든다
      const 운 = rand();
      const 최종 = 운 < 0.14 ? '합격' : 운 < 0.24 ? '충원합격' : '불합격';
      const 일단계 = 유형 === '학생부위주(종합)' ? (운 < 0.4 ? '합격' : '불합격') : '';
      const 등록 = 최종 !== '불합격' && !등록함 ? (등록함 = true, '등록') : '';
      grid.push([
        3, 반, 번호, 이름, 대학, 지역, '수시', 유형, 이름표, 뽑아(모집단위), 계열,
        전교과, 조합, 일단계, 최종,
        최종 === '불합격' ? (rand() < 0.5 ? '서류 평가 미흡' : '') : '',
        최종 === '충원합격' ? String(1 + Math.floor(rand() * 9)) : '',
        등록,
        ...수능
      ]);
    }
  }

  // 학년도 열은 두지 않는다. 고3 년도를 사람이 정하는 길을 체험에서도 그대로 지난다 (§2)
  void schoolYear;
  return grid;
}

/**
 * 예시 양식을 xlsx 바이트열로 만든다.
 *
 * @param {Parameters<typeof sampleGrid>[0]} [options]
 * @returns {Uint8Array}
 */
export function sampleWorkbook(options) {
  const workbook = sheetUtils.book_new();
  sheetUtils.book_append_sheet(workbook, sheetUtils.aoa_to_sheet(sampleGrid(options)), '진학결과');
  return new Uint8Array(writeWorkbook(workbook, { type: 'array', bookType: 'xlsx' }));
}

