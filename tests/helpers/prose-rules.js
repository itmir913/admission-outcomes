/**
 * 한 줄에서 물러난 말을 찾는다.
 *
 * @param {string} line
 * @returns {{was: string, use: string, found: string}[]}
 */
export function retiredIn(line) {
  if (line.includes(SKIP_LINE)) return [];
  const hits = [];
  for (const [pattern, was, use] of RULES) {
    const matched = line.match(new RegExp(pattern, 'u'));
    if (matched) hits.push({ was, use, found: matched[0] });
  }
  return hits;
}
